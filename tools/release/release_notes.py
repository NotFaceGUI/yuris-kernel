#!/usr/bin/env python3
"""从 conventional commits 生成 GitHub Release 更新日志。

设计约束：
- 只用标准库，本地与 GitHub Actions 跑同一份代码；
- 只读 git，不修改工作区，不创建 tag；
- 首次发布（没有上一个 v* tag）也能生成完整日志；
- 输出不含时间戳，便于本地断言和人工复核。

用法见 docs/release.md。
"""

from __future__ import annotations

import argparse
import html
import os
import re
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path
from urllib.parse import quote

GENERATOR = "<!-- generated by tools/release/release_notes.py -->"

TYPE_TITLES: dict[str, str] = {
    "feat": "新功能",
    "fix": "修复",
    "perf": "性能",
    "refactor": "重构",
    "docs": "文档",
    "test": "测试",
    "build": "构建",
    "ci": "CI",
    "chore": "杂项",
    "style": "格式",
    "revert": "回滚",
}
TYPE_ORDER = list(TYPE_TITLES)
OTHER_TITLE = "其他变更"
BREAKING_TITLE = "破坏性变更"

CONVENTIONAL = re.compile(
    r"^(?P<type>[A-Za-z]+)(?:\((?P<scope>[^)]*)\))?(?P<breaking>!)?:\s*(?P<desc>.+)$"
)
BREAKING_BODY = re.compile(
    r"^BREAKING[ -]CHANGE:\s*(.+?)(?=\n\S|\Z)", re.MULTILINE | re.DOTALL
)


class ReleaseError(RuntimeError):
    """发布流程的可预期失败；CLI 会转成非零退出码。"""


@dataclass(frozen=True)
class Commit:
    sha: str
    subject: str
    body: str

    @property
    def short(self) -> str:
        return self.sha[:7]


@dataclass(frozen=True)
class ParsedCommit:
    kind: str
    scope: str
    desc: str
    breaking: bool
    breaking_notes: tuple[str, ...]


def git(
    repo: Path, *args: str, check: bool = True
) -> subprocess.CompletedProcess[str]:
    try:
        proc = subprocess.run(
            ["git", "-C", str(repo), *args],
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
    except OSError as exc:
        raise ReleaseError(f"无法执行 git: {exc}") from exc
    if check and proc.returncode != 0:
        detail = proc.stderr.strip() or proc.stdout.strip()
        raise ReleaseError(f"git {' '.join(args)} 失败: {detail}")
    return proc


def collect_commits(repo: Path, revision_range: str) -> list[Commit]:
    # %x1f 分隔字段、-z 分隔提交，避免提交正文里的换行干扰解析。
    fmt = "%H%x1f%s%x1f%b"
    out = git(repo, "log", "--no-merges", "-z", f"--format={fmt}", revision_range).stdout
    commits: list[Commit] = []
    for record in out.split("\0"):
        record = record.strip("\n")
        if not record:
            continue
        parts = record.split("\x1f", 2)
        if len(parts) != 3:
            raise ReleaseError(f"无法解析 git log 记录: {record[:80]!r}")
        sha, subject, body = parts
        commits.append(Commit(sha=sha.strip(), subject=subject.strip(), body=body))
    return commits


def previous_tag(repo: Path, end_ref: str, exclude: str) -> str | None:
    """返回 end_ref 父提交可达的最近 v* tag；没有则 None。

    用 git describe 而不是按版本号排序：从维护分支发版时，
    最近可达 tag 才是正确的比较基线。
    """
    target = f"{end_ref}^"
    if git(repo, "rev-parse", "--verify", "--quiet", target, check=False).returncode != 0:
        return None
    args = ["describe", "--tags", "--abbrev=0", "--match", "v[0-9]*"]
    if exclude:
        args += ["--exclude", exclude]
    args.append(target)
    proc = git(repo, *args, check=False)
    if proc.returncode != 0:
        return None
    return proc.stdout.strip() or None


def detect_repo_url(repo: Path, override: str | None) -> str | None:
    if override:
        return override.rstrip("/")
    server = os.environ.get("GITHUB_SERVER_URL")
    slug = os.environ.get("GITHUB_REPOSITORY")
    if server and slug:
        return f"{server.rstrip('/')}/{slug}"
    proc = git(repo, "remote", "get-url", "origin", check=False)
    if proc.returncode != 0:
        return None
    url = proc.stdout.strip()
    if not url:
        return None
    match = re.match(r"^git@([^:]+):(.+?)(?:\.git)?$", url)
    if match:
        return f"https://{match.group(1)}/{match.group(2)}"
    match = re.match(r"^ssh://git@([^/]+)/(.+?)(?:\.git)?$", url)
    if match:
        return f"https://{match.group(1)}/{match.group(2)}"
    if url.startswith(("http://", "https://")):
        return re.sub(r"\.git$", "", url).rstrip("/")
    return None


def workspace_version(repo: Path) -> str:
    manifest = repo / "Cargo.toml"
    try:
        with manifest.open("rb") as fh:
            data = tomllib.load(fh)
    except FileNotFoundError as exc:
        raise ReleaseError(f"找不到 {manifest}") from exc
    except tomllib.TOMLDecodeError as exc:
        raise ReleaseError(f"{manifest} 不是合法 TOML: {exc}") from exc
    version = data.get("workspace", {}).get("package", {}).get("version")
    if not isinstance(version, str) or not version:
        raise ReleaseError(
            f"{manifest} 缺少 [workspace.package].version；"
            "发布流程用它校验 tag 与代码版本是否一致"
        )
    return version


def check_version(repo: Path, tag: str) -> None:
    if not tag.startswith("v"):
        raise ReleaseError(f"tag {tag!r} 应以 v 开头（例如 v0.1.0）")
    expected = tag[1:]
    actual = workspace_version(repo)
    if expected != actual:
        raise ReleaseError(
            f"tag {tag} 与 Cargo.toml 的 [workspace.package].version = {actual!r} 不一致；"
            "先提交版本号变更，再打 tag"
        )
    print(f"版本一致: {tag} == Cargo.toml {actual}")


def escape_text(text: str) -> str:
    # 压平空白并转义 HTML 元字符，避免提交信息里的 <T> / A&B 被 Markdown 吞掉。
    return html.escape(" ".join(text.split()), quote=False)


def parse_commit(commit: Commit) -> ParsedCommit:
    match = CONVENTIONAL.match(commit.subject)
    if not match:
        return ParsedCommit(
            kind="",
            scope="",
            desc=commit.subject,
            breaking=False,
            breaking_notes=(),
        )
    notes = tuple(
        " ".join(found.group(1).split())
        for found in BREAKING_BODY.finditer(commit.body)
        if found.group(1).strip()
    )
    return ParsedCommit(
        kind=match.group("type").lower(),
        scope=(match.group("scope") or "").replace("`", "'").strip(),
        desc=match.group("desc").strip(),
        breaking=bool(match.group("breaking")) or bool(notes),
        breaking_notes=notes,
    )


def render_entry(commit: Commit, parsed: ParsedCommit, url: str | None) -> str:
    label = f"`{parsed.scope}`: " if parsed.scope else ""
    if url:
        link = f" ([{commit.short}]({url}/commit/{commit.sha}))"
    else:
        link = f" ({commit.short})"
    lines = [f"- {label}{escape_text(parsed.desc)}{link}"]
    lines.extend(
        f"  - BREAKING CHANGE: {escape_text(note)}" for note in parsed.breaking_notes
    )
    return "\n".join(lines)


def render_notes(
    commits: list[Commit], tag: str, previous: str | None, url: str | None
) -> str:
    lines: list[str] = ["## 更新内容", ""]

    if previous:
        label = f"{previous}...{tag}"
        if url:
            compare = (
                f"{url}/compare/"
                f"{quote(previous, safe='')}...{quote(tag, safe='')}"
            )
            lines.append(f"**完整变更**: [{label}]({compare})")
        else:
            lines.append(f"**完整变更**: {label}")
    else:
        lines.append("首个版本，包含仓库初始化以来的全部提交。")
    lines.append("")

    if not commits:
        lines.append("本版本没有代码变更。")
        lines.append("")
        lines.append(GENERATOR)
        return "\n".join(lines).rstrip() + "\n"

    breaking: list[tuple[Commit, ParsedCommit]] = []
    groups: dict[str, list[tuple[Commit, ParsedCommit]]] = {kind: [] for kind in TYPE_ORDER}
    other: list[tuple[Commit, ParsedCommit]] = []

    for commit in commits:
        parsed = parse_commit(commit)
        if parsed.breaking:
            breaking.append((commit, parsed))
        elif parsed.kind in groups:
            groups[parsed.kind].append((commit, parsed))
        else:
            other.append((commit, parsed))

    if breaking:
        lines.extend([f"### {BREAKING_TITLE}", ""])
        lines.extend(render_entry(commit, parsed, url) for commit, parsed in breaking)
        lines.append("")

    for kind in TYPE_ORDER:
        entries = groups[kind]
        if not entries:
            continue
        lines.extend([f"### {TYPE_TITLES[kind]} ({kind})", ""])
        lines.extend(render_entry(commit, parsed, url) for commit, parsed in entries)
        lines.append("")

    if other:
        lines.extend([f"### {OTHER_TITLE}", ""])
        lines.extend(render_entry(commit, parsed, url) for commit, parsed in other)
        lines.append("")

    lines.append(GENERATOR)
    return "\n".join(lines).rstrip() + "\n"


def build_notes(
    repo: Path,
    tag: str,
    to_ref: str | None = None,
    from_ref: str | None = None,
    repo_url: str | None = None,
) -> tuple[str, str, str | None]:
    repo = repo.resolve()
    target = to_ref or f"refs/tags/{tag}"
    if (
        git(repo, "rev-parse", "--verify", "--quiet", f"{target}^{{commit}}", check=False)
        .returncode
        != 0
    ):
        raise ReleaseError(f"目标 ref 不存在: {target}")

    base = from_ref or previous_tag(repo, target, tag)
    revision_range = f"{base}..{target}" if base else target
    commits = collect_commits(repo, revision_range)
    url = detect_repo_url(repo, repo_url)
    return render_notes(commits, tag, base, url), revision_range, url


def write_text(text: str, output: str) -> None:
    if output == "-":
        sys.stdout.write(text)
        if not text.endswith("\n"):
            sys.stdout.write("\n")
        return
    path = Path(output)
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    print(f"已写入 {path} ({len(text.encode('utf-8'))} 字节)", file=sys.stderr)


def env_dry_run() -> bool:
    return os.environ.get("YU_RELEASE_DRY_RUN", "").strip().lower() in {
        "1",
        "true",
        "yes",
    }


def gh_run(
    args: list[str], gh_cmd: list[str] | None = None
) -> subprocess.CompletedProcess[str]:
    cmd = [*(gh_cmd or ["gh"]), *args]
    try:
        return subprocess.run(
            cmd,
            capture_output=True,
            text=True,
            encoding="utf-8",
            errors="replace",
        )
    except OSError as exc:
        raise ReleaseError(f"无法执行 {cmd[0]}: {exc}") from exc


def release_missing(proc: subprocess.CompletedProcess[str]) -> bool:
    text = proc.stderr.lower()
    return "release not found" in text or "http 404" in text


def is_prerelease(tag: str) -> bool:
    version = tag[1:] if tag.startswith("v") else tag
    # SemVer 的预发布段在第一个 '-' 之后；'+' 之后是 build metadata，不算预发布。
    return "-" in version.split("+", 1)[0]


def publish(
    tag: str,
    notes_file: Path,
    *,
    dry_run: bool = False,
    gh_cmd: list[str] | None = None,
) -> None:
    notes_file = notes_file.resolve()
    if not notes_file.is_file():
        raise ReleaseError(f"notes 文件不存在: {notes_file}")
    if not notes_file.read_text(encoding="utf-8").strip():
        raise ReleaseError(f"notes 文件为空: {notes_file}")

    prerelease = is_prerelease(tag)
    if dry_run:
        kind = "预发布" if prerelease else "正式"
        print(f"[dry-run] 将检查 Release {tag}（{kind}）：不存在则 create，已存在则 edit")
        print(f"[dry-run] notes: {notes_file}")
        return

    view = gh_run(["release", "view", tag], gh_cmd)
    if view.returncode == 0:
        args = [
            "release",
            "edit",
            tag,
            "--title",
            tag,
            "--notes-file",
            str(notes_file),
            "--draft=false",
            "--prerelease" if prerelease else "--prerelease=false",
        ]
        action = "更新"
    elif release_missing(view):
        args = [
            "release",
            "create",
            tag,
            "--verify-tag",
            "--title",
            tag,
            "--notes-file",
            str(notes_file),
        ]
        if prerelease:
            args.append("--prerelease")
        action = "创建"
    else:
        detail = view.stderr.strip() or view.stdout.strip()
        raise ReleaseError(f"gh release view {tag} 失败: {detail}")

    print(f"执行: gh {' '.join(args)}")
    result = gh_run(args, gh_cmd)
    if result.returncode != 0:
        detail = result.stderr.strip() or result.stdout.strip()
        raise ReleaseError(f"gh release {'edit' if action == '更新' else 'create'} 失败: {detail}")
    print(f"Release {tag} 已{action}")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="yuris-kernel tag 发布：更新日志生成、版本校验、Release 创建/更新"
    )
    sub = parser.add_subparsers(dest="command", required=True)

    notes = sub.add_parser("notes", help="生成 Release 更新日志")
    notes.add_argument("--repo", default=".", help="git 仓库路径（默认当前目录）")
    notes.add_argument("--tag", required=True, help="发布 tag，例如 v0.1.0")
    notes.add_argument(
        "--to",
        default=None,
        help="目标 ref（默认 refs/tags/<tag>；本地预览可用 HEAD）",
    )
    notes.add_argument(
        "--from",
        dest="from_ref",
        default=None,
        help="比较基线 ref；默认取目标父提交可达的最近 v* tag",
    )
    notes.add_argument(
        "--output", "-o", default="-", help="输出文件；- 表示 stdout（默认）"
    )
    notes.add_argument(
        "--repo-url", default=None, help="覆盖仓库链接（默认从 origin 或 GITHUB_REPOSITORY 推导）"
    )

    check = sub.add_parser("check-version", help="校验 tag 与 Cargo.toml 工作区版本一致")
    check.add_argument("--repo", default=".", help="git 仓库路径（默认当前目录）")
    check.add_argument("--tag", required=True, help="发布 tag，例如 v0.1.0")

    pub = sub.add_parser("publish", help="创建或更新 GitHub Release")
    pub.add_argument("--tag", required=True, help="发布 tag，例如 v0.1.0")
    pub.add_argument("--notes-file", required=True, help="更新日志文件")
    pub.add_argument(
        "--dry-run",
        action="store_true",
        help="只打印将要执行的动作；也可用 YU_RELEASE_DRY_RUN=1",
    )

    return parser


def main(argv: list[str] | None = None) -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")

    args = build_parser().parse_args(argv)
    try:
        if args.command == "notes":
            text, revision_range, url = build_notes(
                Path(args.repo),
                args.tag,
                to_ref=args.to,
                from_ref=args.from_ref,
                repo_url=args.repo_url,
            )
            write_text(text, args.output)
            print(
                f"更新日志范围: {revision_range}；仓库链接: {url or '(无)'}",
                file=sys.stderr,
            )
        elif args.command == "check-version":
            check_version(Path(args.repo), args.tag)
        elif args.command == "publish":
            publish(
                args.tag,
                Path(args.notes_file),
                dry_run=args.dry_run or env_dry_run(),
            )
    except ReleaseError as exc:
        if os.environ.get("GITHUB_ACTIONS") == "true":
            print(f"::error::{exc}")
        print(f"错误: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
